GRADES = {10: "دهم", 11: "یازدهم", 12: "دوازدهم"}


class Command(BaseCommand):
    help = "Seed grade 10–12 academic planning options; safe to run repeatedly."

    @transaction.atomic
    def handle(self, *args, **options):
        counts = {"grades": 0, "fields": 0, "subjects": 0, "chapters": 0, "topics": 0}
        for year, grade_name in GRADES.items():
            grade, created = Grade.objects.get_or_create(name=grade_name, defaults={"ordering": year})
            counts["grades"] += created
            for field_order, (field_name, by_year) in enumerate(SPECIALIZED.items(), 1):
                field, created = Field.objects.get_or_create(grade=grade, name=field_name, defaults={"ordering": field_order})
                counts["fields"] += created
                subjects = {**COMMON[year], **by_year[year]}
                for subject_order, (subject_name, chapters) in enumerate(subjects.items(), 1):
                    subject, created = Subject.objects.get_or_create(field=field, name=subject_name, defaults={"ordering": subject_order})
                    counts["subjects"] += created
                    for chapter_order, (chapter_name, topics) in enumerate(chapters.items(), 1):
                        chapter, created = Chapter.objects.get_or_create(subject=subject, name=chapter_name, defaults={"ordering": chapter_order})
                        counts["chapters"] += created
                        for topic_order, topic_name in enumerate(topics, 1):
                            _, created = Topic.objects.get_or_create(chapter=chapter, name=topic_name, defaults={"ordering": topic_order})
                            counts["topics"] += created
        self.stdout.write(self.style.SUCCESS(f"Academic taxonomy ready. New records: {counts}"))
